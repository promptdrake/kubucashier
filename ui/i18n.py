# Current global language state ('en' or 'id')
CURRENT_LANGUAGE = "en"


def set_language(lang_code: str):
    """Sets active language ('en' or 'id')."""
    global CURRENT_LANGUAGE
    if lang_code in TRANSLATIONS:
        CURRENT_LANGUAGE = lang_code


def get_language() -> str:
    """Returns active language code."""
    return CURRENT_LANGUAGE


def t(key: str, **kwargs: Any) -> str:
    """Retrieves translated string for the current language with optional keyword formatting."""
    lang_dict = TRANSLATIONS.get(CURRENT_LANGUAGE, TRANSLATIONS["en"])
    text = lang_dict.get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
